#!/bin/sh
# Write common/grimpVersionInfo.h (not tracked) for common/grimpVersion.c: the mosaicSource
# version (VERSION, bumped on every commit by the pre-commit hook) and the commit of
# mosaicSource and of each library repo linked into the binaries. A repo with uncommitted
# changes is marked "-dirty.<first 8 of the hash of git diff HEAD>", so even a build from an
# uncommitted tree names its exact source. The header is only rewritten when it changes, so an
# unchanged tree recompiles nothing. Run by the mosaicSource Makefile on every make.
src=$(cd "$(dirname "$0")/.." && pwd)
progs=$(dirname "$src")
out="$src/common/grimpVersionInfo.h"

commitOf() {
    c=$(git -C "$1" rev-parse --short HEAD 2>/dev/null) || { echo unknown; return; }
    if [ -n "$(git -C "$1" status --porcelain --untracked-files=no 2>/dev/null)" ]; then
        c="$c-dirty.$(git -C "$1" diff HEAD 2>/dev/null | git hash-object --stdin | cut -c1-8)"
    fi
    echo "$c"
}

version=$(head -n 1 "$src/VERSION" 2>/dev/null | tr -d ' \r')
[ -n "$version" ] || version=unknown
libs=""
for repo in clib gdalIO cRecipes triangle; do
    libs="$libs${libs:+, }$repo $(commitOf "$progs/$repo")"
done
tmp="$out.tmp.$$"
{
    echo "/* Generated by scripts/makeVersionHeader.sh -- do not edit or commit */"
    echo "#define MOSAICSOURCE_VERSION \"$version\""
    echo "#define MOSAICSOURCE_COMMIT \"$(commitOf "$src")\""
    echo "#define MOSAICSOURCE_LIBCOMMITS \"$libs\""
} > "$tmp"
if cmp -s "$tmp" "$out"; then
    rm -f "$tmp"
else
    mv "$tmp" "$out"
fi
